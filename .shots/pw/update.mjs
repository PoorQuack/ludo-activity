// Live check of the update notice: announce, restart the server, page reconnects.
import chromium from '@sparticuz/chromium';
import { chromium as pw } from 'playwright-core';
import { execSync, spawn } from 'node:child_process';
import fs from 'node:fs';
const S = process.env.HOME + '/mnt/ludo-activity/.shots/';
const W = '/tmp/prev-upd';
const b = await pw.launch({ executablePath: await chromium.executablePath(), args: chromium.args, headless: true });
const p = await b.newPage({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true });
const errors = []; p.on('pageerror', (e) => errors.push(e.message));
p.on('dialog', (d) => d.accept());
const sys = () => p.$$eval('.chat-log .system', (ls) => [...new Set(ls.map((l) => l.textContent))]);
const toast = () => p.$eval('#toast', (t) => (t.classList.contains('hidden') ? '(hidden)' : `[${t.className}] ${t.textContent}`));
await p.goto('http://localhost:3990/?name=Ann', { waitUntil: 'networkidle' }); await p.waitForTimeout(600);
await p.click('#create-btn'); await p.waitForTimeout(500);
await p.click('#fill-btn'); await p.waitForTimeout(400);
await p.click('#start-btn'); await p.waitForTimeout(3000);
const turnBefore = await p.textContent('#turn-text');
console.log('announce:', execSync('curl -s -X POST localhost:3990/api/admin/announce').toString());
await p.waitForTimeout(800);
console.log('toast after announce:', await toast());
console.log('chat system lines:', await sys());
await p.screenshot({ path: S + 'upd-1-announce.png' });
const pid = fs.readFileSync('/tmp/pw/sp', 'utf8').trim();
process.kill(Number(pid), 'SIGINT');
await p.waitForTimeout(250);
console.log('toast at restart:', await toast());
await p.waitForTimeout(700);
console.log('loading shown:', await p.isVisible('#loading'), '|', await p.textContent('#loading-text'));
await p.screenshot({ path: S + 'upd-2-restarting.png' });
console.log('rooms file saved:', fs.existsSync(W + '/data/rooms.json'));
await p.waitForTimeout(2000);
const child = spawn('node', ['server/index.js'], { cwd: W, env: { ...process.env, PORT: '3990', DATA_FILE: W + '/data/p.json', ALLOW_GUESTS: 'true' }, stdio: ['ignore', fs.openSync(W + '/server2.log', 'w'), fs.openSync(W + '/server2.log', 'a')], detached: true });
fs.writeFileSync('/tmp/pw/sp', String(child.pid));
for (let i = 0; i < 40 && await p.isVisible('#loading'); i++) await p.waitForTimeout(500);
await p.waitForTimeout(500);
console.log('back: loading shown:', await p.isVisible('#loading'));
console.log('toast after reconnect:', await toast());
console.log('chat system lines:', await sys());
console.log('turn before/after:', turnBefore, '|', await p.textContent('#turn-text'));
await p.screenshot({ path: S + 'upd-3-back.png' });
console.log('errors:', errors.join(' / ') || 'none');
await b.close();
process.kill(child.pid);
