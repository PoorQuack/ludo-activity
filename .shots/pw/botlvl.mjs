import chromium from '@sparticuz/chromium';
import { chromium as pw } from 'playwright-core';
const S = process.env.HOME + '/mnt/ludo-activity/.shots/';
const b = await pw.launch({ executablePath: await chromium.executablePath(), args: chromium.args, headless: true });
const p = await b.newPage({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, isMobile: true, hasTouch: true });
const errs = []; p.on('pageerror', (e) => errs.push(e.message));
await p.goto('http://localhost:3990/?name=Ann', { waitUntil: 'networkidle' }); await p.waitForTimeout(700);
await p.click('#create-btn'); await p.waitForTimeout(500);
await p.click('#fill-btn'); await p.waitForTimeout(500);
const sels = await p.$$('.bot-level');
console.log('pickers:', sels.length);
await sels[0].selectOption('impossible'); await p.waitForTimeout(500);
await (await p.$$('.bot-level'))[1].selectOption('easy'); await p.waitForTimeout(500);
await (await p.$$('.bot-level'))[2].selectOption('hard'); await p.waitForTimeout(500);
console.log('levels:', await p.$$eval('.bot-level', (s) => s.map((x) => x.value)));
await p.screenshot({ path: S + 'botlevels.png' });
await p.click('#start-btn'); await p.waitForTimeout(3000);
console.log('in game subs:', await p.$$eval('.seat-sub', (s) => s.map((x) => x.textContent)));
console.log('errors:', errs.join(' / ') || 'none');
await b.close();
