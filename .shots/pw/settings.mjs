import chromium from '@sparticuz/chromium';
import { chromium as pw } from 'playwright-core';
const S = process.env.HOME + '/mnt/ludo-activity/.shots/';
const b = await pw.launch({ executablePath: await chromium.executablePath(), args: chromium.args, headless: true });
const p = await b.newPage({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, isMobile: true, hasTouch: true });
const errs = []; p.on('pageerror', (e) => errs.push(e.message));
await p.goto('http://localhost:3990/?name=Ann', { waitUntil: 'networkidle' }); await p.waitForTimeout(700);
await p.click('.menu-tools [data-player-btn]'); await p.waitForTimeout(400);
await p.screenshot({ path: S + 'settings-menu.png' });
await p.click('#player-pop [data-gfx="smooth"]'); await p.waitForTimeout(200);
await p.click('#player-pop [data-cb]'); await p.waitForTimeout(200);
console.log('after taps:', await p.evaluate(() => ({ smooth: localStorage.getItem('ludo-smooth'), active: [...document.querySelectorAll('[data-gfx].active')].map((b) => b.dataset.gfx), cb: document.querySelector('[data-cb]').textContent, lite: !!window.__r?.lite })));
await p.keyboard.press('Escape');
await p.click('#create-btn'); await p.waitForTimeout(500);
await p.click('#fill-btn'); await p.waitForTimeout(300);
await p.click('#start-btn'); await p.waitForTimeout(1500);
await p.click('.panel-head [data-player-btn]'); await p.waitForTimeout(400);
await p.screenshot({ path: S + 'settings-game.png' });
console.log('errors:', errs.join(' / ') || 'none');
await b.close();
